-- Social Network module: tables + RBAC + localized strings.
--
-- IMPORTANT: unlike most modules, this one stores its data in acore_characters
-- (player-generated content is bound to characters), while RBAC lives in
-- acore_auth and module strings live in acore_world.
--
-- Idempotent: every INSERT is preceded by a matching DELETE, tables use
-- CREATE TABLE IF NOT EXISTS.

-- ============================================================
-- Tables (apply to acore_characters)
-- ============================================================

CREATE TABLE IF NOT EXISTS `socn_profiles` (
  `guid` int unsigned NOT NULL,
  `guildId` int unsigned NOT NULL DEFAULT 0,
  `status` varchar(255) NOT NULL DEFAULT '',
  PRIMARY KEY (`guid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `socn_posts` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `authorGuid` int unsigned NOT NULL,
  `text` varchar(255) NOT NULL,
  `repostOf` int unsigned NOT NULL DEFAULT 0,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_socn_posts_author` (`authorGuid`),
  KEY `idx_socn_posts_repost` (`repostOf`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `socn_post_likes` (
  `postId` int unsigned NOT NULL,
  `voterGuid` int unsigned NOT NULL,
  PRIMARY KEY (`postId`, `voterGuid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `socn_follows` (
  `followerGuid` int unsigned NOT NULL,
  `targetGuid` int unsigned NOT NULL,
  PRIMARY KEY (`followerGuid`, `targetGuid`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- ============================================================
-- RBAC (apply to acore_auth)
-- ============================================================

